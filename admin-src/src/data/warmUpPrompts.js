// Per skill: the prompt and the two pieces of material the admin pastes, in the
// order the prompt lists them.
export const WARMUP_PROMPTS = {
  listening: {
    title: 'Prompt warm-up Listening',
    prompt: LISTENING_PROMPT,
    fields: [
      { key: 'questions', label: 'IELTS Listening Questions', placeholder: 'Dán câu hỏi của bài nghe (Questions 1–10…)' },
      { key: 'source', label: 'IELTS Listening Transcript', placeholder: 'Dán transcript của bài nghe' },
    ],
  },
  reading: {
    title: 'Prompt warm-up Reading',
    prompt: READING_PROMPT,
    fields: [
      { key: 'source', label: 'IELTS Reading Passage', placeholder: 'Dán bài đọc (giữ ký hiệu đoạn A, B, C… nếu có)' },
      { key: 'questions', label: 'IELTS Reading Questions', placeholder: 'Dán câu hỏi của bài đọc' },
    ],
  },
};

// Prompt + the pasted material, ready to send to an AI in one message. Empty
// fields are left out so "copy prompt only" and "copy with material" share one path.
export function buildWarmUpMessage(skill, values = {}) {
  const cfg = WARMUP_PROMPTS[skill];
  if (!cfg) return '';
  const parts = cfg.fields
    .map((f, i) => ({ f, i, text: String(values[f.key] || '').trim() }))
    .filter(p => p.text)
    .map(p => `## ${p.i + 1}. ${p.f.label}\n\n${p.text}`);
  if (!parts.length) return cfg.prompt;
  return `${cfg.prompt}\n\n---\n\n# TEACHER INPUT\n\n${parts.join('\n\n')}\n`;
}
