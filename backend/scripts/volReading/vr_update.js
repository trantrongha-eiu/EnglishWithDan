'use strict';
// Push a corrected draft (web/vol<V>/draft/t<T>p<P>.json, rebuilt by vr_build.js) onto its already-imported passage
// (web/vol<V>/imported.json): replaces title, content, questionGroups, questionRange only (cover, isActive, tags kept).
// Backs the old document up to web/vol<V>/backup/<name>_<time>.json; the update is conditional on updatedAt (a concurrent
// admin edit is never overwritten). Prints how many attempts already use the passage (old answers are graded on save,
// so a changed key does not rewrite them).
//   node vr_update.js <vol> <t6p3 …> [--apply]
require('dotenv').config({ path: require('path').join(__dirname, '..', '..', '.env'), quiet: true });
const fs = require('fs'), path = require('path');
const mongoose = require('mongoose');
const [vol, ...rest] = process.argv.slice(2);
const apply = rest.includes('--apply');
const names = rest.filter(a => !a.startsWith('--'));
const dir = path.join(__dirname, 'web', `vol${vol}`);
const imported = JSON.parse(fs.readFileSync(path.join(dir, 'imported.json'), 'utf8'));

(async () => {
  await mongoose.connect(process.env.MONGO_URI);
  const db = mongoose.connection.db;
  try {
    for (const n of names) {
      const id = imported[n];
      if (!id) { console.log(`✗ ${n} not imported`); continue; }
      const { doc } = JSON.parse(fs.readFileSync(path.join(dir, 'draft', `${n}.json`), 'utf8'));
      const _id = new mongoose.Types.ObjectId(id);
      const old = await db.collection('passages').findOne({ _id });
      const practice = await db.collection('readingpracticeattempts').countDocuments({ passageId: _id });
      const full = await db.collection('testattempts').countDocuments({ passagesUsed: _id });
      const keys = d => d.questionGroups.flatMap(g => g.questions.map(q => `${q.questionNumber}=${q.correctAnswer}`));
      const ko = keys(old), kn = keys(doc);
      const changed = kn.filter((k, i) => k !== ko[i]);
      console.log(`${n} "${old.title}" → keys changed: ${changed.join(', ') || 'none'}; content ${old.content === doc.content ? 'same' : 'changed'}; attempts: ${practice} practice, ${full} full-test`);
      if (!apply) continue;
      fs.mkdirSync(path.join(dir, 'backup'), { recursive: true });
      fs.writeFileSync(path.join(dir, 'backup', `${n}_${Date.now()}.json`), JSON.stringify(old, null, 1));
      // keep the stored question/group _ids out of the comparison: fresh ones are generated by Mongoose shape here
      const groups = doc.questionGroups.map(g => ({ ...g, _id: new mongoose.Types.ObjectId(), questions: g.questions.map(q => ({ ...q, _id: new mongoose.Types.ObjectId() })) }));
      const r = await db.collection('passages').updateOne({ _id, updatedAt: old.updatedAt },
        { $set: { title: doc.title, content: doc.content, questionGroups: groups, questionRange: doc.questionRange, updatedAt: new Date() } });
      console.log(`   ${r.modifiedCount ? '✓ updated' : '✗ changed meanwhile — not updated'}`);
    }
    if (!apply) console.log('dry run — re-run with --apply');
  } finally { await mongoose.disconnect(); }
})().catch(e => { console.error(e); process.exit(1); });
