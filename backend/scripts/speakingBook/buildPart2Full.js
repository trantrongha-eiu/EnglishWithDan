// "📄 Xem full bài mẫu" on speaking-part2.html: each of the 7 master stories
// exactly as it stands in IELTS_Speaking_Part2_Master_Framework_v3.docx
// (repo root, local only) — headings, sentences, WHY table, boxes, vocab
// table — in the book's order. Writes backend/data/speakingPart2Full.js.
//
//   py backend/scripts/speakingBook/extractDocx.py IELTS_Speaking_Part2_Master_Framework_v3.docx fw.json
//   node backend/scripts/speakingBook/buildPart2Full.js fw.json
//
// Block shapes (rendered by fullBlocks() in frontend/js/speaking-part2.js):
//   {k:'sub', t}                  "Nhóm chủ đề: … · Câu hỏi gốc: …"
//   {k:'h', t}                    "1. Giới thiệu", "▼ TỪ ĐÂY…", "★ Từ vựng…"
//   {k:'p', t}                    a paragraph; **bold** kept as markers
//   {k:'box', label, lines[]}     the book's one-cell coloured boxes
//   {k:'table', head, rows[[cell]]}  head = first row when it is all bold;
//                                 a one-cell row inside = section row
//   cells keep "\n" between their paragraphs.
// Re-run after editing the framework docx.
'use strict';

const fs = require('fs');
const path = require('path');

const src = process.argv[2];
if (!src) { console.error('usage: node buildPart2Full.js <extract.json>'); process.exit(1); }
const blocks = JSON.parse(fs.readFileSync(src, 'utf8'));
const DATA = require('../../data/speakingPart2');
const OUT = path.join(__dirname, '..', '..', 'data', 'speakingPart2Full.js');

const norm = (s) => String(s || '').replace(/ /g, ' ').replace(/\t/g, ' ').replace(/\*\*\s*\*\*/g, '').trim();
const unbold = (s) => norm(s).replace(/\*\*/g, '').trim();
const allBold = (s) => { const t = norm(s); return /^\*\*[^*]+\*\*$/.test(t); };
const cellText = (cell) => cell.map(norm).filter(Boolean).join('\n');

// Story starts: "**01 · Mrs Hoa — …**" without the table-of-contents page number.
const STORY_RE = /^(0[1-7]) · /;
const END_RE = /^08 · /;
const byNo = new Map(DATA.stories.map((s) => [s.no, s]));

const out = {};
let cur = null;
for (const b of blocks) {
  if (b.k === 'p') {
    const t = unbold(b.t);
    if (/\s\d+$/.test(norm(b.t).replace(/\*\*/g, '')) && /\t/.test(b.t)) continue; // TOC line
    const m = STORY_RE.exec(t);
    if (m && allBold(b.t)) {
      const st = byNo.get(m[1]);
      if (!st) throw new Error('no story ' + m[1]);
      cur = out[st.id] = { title: t, blocks: [] };
      continue;
    }
    if (END_RE.test(t)) { cur = null; continue; }
    if (!cur || !t) continue;
    if (/^Nhóm chủ đề:/.test(t)) cur.blocks.push({ k: 'sub', t });
    else if (allBold(b.t) && (/^\d+\.\s/.test(t) || /^[▼★]/.test(t))) cur.blocks.push({ k: 'h', t });
    else cur.blocks.push({ k: 'p', t: norm(b.t) });
  } else if (b.k === 'tbl' && cur) {
    const rows = b.rows;
    if (rows.length === 1 && rows[0].length === 1) {
      const paras = rows[0][0].map(norm).filter(Boolean);
      const first = paras[0] || '';
      if (allBold(first)) cur.blocks.push({ k: 'box', label: unbold(first), lines: paras.slice(1) });
      else cur.blocks.push({ k: 'box', label: '', lines: paras });
      continue;
    }
    const cells = rows.map((r) => r.map(cellText));
    const isHead = cells[0].length > 1 && cells[0].every((c) => allBold(c));
    cur.blocks.push({
      k: 'table',
      head: isHead ? cells[0].map(unbold) : null,
      rows: isHead ? cells.slice(1) : cells,
    });
  }
}

const ids = Object.keys(out);
if (ids.length !== DATA.stories.length) throw new Error('found ' + ids.length + ' stories, expected ' + DATA.stories.length);
const body = '\'use strict\';\n\n' +
  '// GENERATED by backend/scripts/speakingBook/buildPart2Full.js from\n' +
  '// IELTS_Speaking_Part2_Master_Framework_v3.docx — do not edit by hand.\n' +
  '// "📄 Xem full bài mẫu" on speaking-part2.html (Premium, via\n' +
  '// GET /api/speaking-part2/full/:storyId).\n\n' +
  'module.exports = ' + JSON.stringify(out, null, 1) + ';\n';
fs.writeFileSync(OUT, body);
ids.forEach((id) => console.log(id.padEnd(12), out[id].blocks.length, 'blocks —', out[id].title));
console.log('→', path.relative(process.cwd(), OUT));
